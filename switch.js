let dia = 5;
switch (dia){
    case 1:
        console.log("DOMINGO");
        break;
    case 2:
        console.log("SEGUNDA-FEIRA");
        break;
    case 3:
        console.log("TERÇA-FEIRA");
        break;
    case 4:
        console.log("QUARTA-FEIRA");
        break;
    case 5:
        console.log("QUINTA-FEIRA");
        break;
    case 6:
        console.log("SEXTA-FEIRA");
        break;
    case 7:
        console.log("SABADO");
        break;
    default:
        console.log("NUMERO INVALIDO.");
}
